export function claveRaza(raza) {
  const t = String(raza || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (t.includes("isa") && t.includes("brown")) return "isa";
  if (t.includes("lohmann") && t.includes("brown")) return "lohmann";
  if (t.includes("hyline") && t.includes("w36")) return "w36";
  if (t.includes("hyline") && t.includes("brown") && !t.includes("silver") && !t.includes("max")) return "hyline";
  return null;
}

export function referenciaRaza(raza, semana) {
  const ficha = REFERENCIAS_RAZAS[claveRaza(raza)];
  if (!ficha || !Number.isFinite(semana) || semana < 0) return null;
  const edadSemana = Math.max(1, Math.ceil(semana));
  const fila = ficha.semanas[edadSemana];
  return fila ? { ...fila, semana: edadSemana, fuente: ficha.fuente, nombre: ficha.nombre, tipo: ficha.tipo } : null;
}

export function valorCentral(rango) {
  return rango ? (rango[0] + rango[1]) / 2 : null;
}
